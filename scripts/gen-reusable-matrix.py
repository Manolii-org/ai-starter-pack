#!/usr/bin/env python3
"""Generate the Input/Secret/Output matrix in REUSABLE-WORKFLOWS.md.

The matrix is rendered from each `.github/workflows/*-reusable.yml`
`on.workflow_call` schema, between the markers below. Never hand-edit the
generated block; edit the workflow and re-run:

    python3 scripts/gen-reusable-matrix.py          # rewrite the block
    python3 scripts/gen-reusable-matrix.py --check  # exit 1 on drift (CI)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WORKFLOWS = ROOT / ".github" / "workflows"
DOC = WORKFLOWS / "REUSABLE-WORKFLOWS.md"
BEGIN = "<!-- reusable-matrix:begin (generated by scripts/gen-reusable-matrix.py; do not edit) -->"
END = "<!-- reusable-matrix:end -->"


def _call(path: Path) -> dict | None:
    spec = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    on = spec.get("on", spec.get(True)) or {}
    if not isinstance(on, dict) or "workflow_call" not in on:
        return None
    return on["workflow_call"] or {}


def _default(value) -> str:
    """Render a default in full so `--check` sees every change to it.

    Newlines become a literal `\\n` and pipes are escaped, so a multi-line or
    piped default stays on one Markdown table row without changing meaning.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    text = str(value).rstrip("\n")
    return text.replace("\\", "\\\\").replace("\n", "\\n").replace("|", "\\|")


def _input(name: str, spec: dict) -> str:
    """One input's full contract: name, declared default, type, required.

    Every attribute a caller depends on is rendered independently, so `--check`
    sees a change to any of them: a default is shown whenever one is declared
    (`=''` for an empty string, even on a required input); a non-string type is
    named; `(req)` marks required inputs.
    """
    entry = name
    if "default" in spec and spec["default"] is not None:
        value = _default(spec["default"])
        entry += f"={value}" if value else "=''"
    if spec.get("type", "string") != "string":
        entry += f": {spec['type']}"
    entry = f"`{entry}`"
    return entry + " (req)" if spec.get("required") else entry


def _inputs(call: dict) -> str:
    items = [_input(name, spec or {}) for name, spec in (call.get("inputs") or {}).items()]
    return ", ".join(items) or "none"


def _secrets(call: dict) -> str:
    items = [f"`{name}`" + (" (req)" if (spec or {}).get("required") else "")
             for name, spec in (call.get("secrets") or {}).items()]
    return ", ".join(items) or "none"


def _outputs(call: dict) -> str:
    return ", ".join(f"`{name}`" for name in (call.get("outputs") or {})) or "none"


def render() -> str:
    rows = [
        BEGIN,
        "",
        "| Workflow | Inputs (`name=default: type`; type shown when not string; `(req)` = required) | Secrets | Outputs |",
        "|----------|--------|---------|---------|",
    ]
    for path in sorted(WORKFLOWS.glob("*-reusable.yml")):
        call = _call(path)
        if call is None:
            continue
        name = path.name[: -len(".yml")]
        rows.append(f"| **{name}** | {_inputs(call)} | {_secrets(call)} | {_outputs(call)} |")
    rows += ["", END]
    return "\n".join(rows)


def splice(text: str, block: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: generated-block markers missing")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed block is stale")
    args = parser.parse_args()
    current = DOC.read_text(encoding="utf-8")
    wanted = splice(current, render())
    if args.check:
        if current != wanted:
            print(f"{DOC.relative_to(ROOT)}: reusable matrix is stale — run "
                  "python3 scripts/gen-reusable-matrix.py", file=sys.stderr)
            return 1
        print("reusable matrix up to date")
        return 0
    if current != wanted:
        DOC.write_text(wanted, encoding="utf-8")
        print(f"updated {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
