#!/usr/bin/env python3
"""Ratchet zizmor workflow-security findings against a committed baseline.

New findings FAIL. Findings that disappear also FAIL until the baseline is
regenerated, so the baseline only ever shrinks (same burn-down contract as the
registry-lint allowlists).

A finding's fingerprint is its audit id, file, annotation and the source text
it points at, with commit SHAs and ``# vX.Y.Z`` comments removed. Line numbers
are not part of it, and neither are action digests, so unrelated edits and
routine Renovate pin rotations do not churn the baseline.

Usage:
    python3 scripts/workflow-security-ratchet.py                   # check
    python3 scripts/workflow-security-ratchet.py --write-baseline  # accept current state
    python3 scripts/workflow-security-ratchet.py --input zz.json   # use precomputed output

Exit codes: 0 matches baseline, 1 drift, 2 scanner/usage error.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

DEFAULT_BASELINE = Path("config/zizmor-baseline.json")
DEFAULT_PATHS = [".github/workflows", ".github/actions"]
SHA_RE = re.compile(r"\b[0-9a-f]{40}\b")
VERSION_COMMENT_RE = re.compile(r"#\s*v?\d+(?:\.\d+)*[\w.-]*")
WS_RE = re.compile(r"\s+")


def _primary(finding: dict) -> dict:
    locations = finding.get("locations") or []
    for loc in locations:
        if loc.get("symbolic", {}).get("kind") == "Primary":
            return loc
    return locations[0] if locations else {}


def _path(loc: dict) -> str:
    key = loc.get("symbolic", {}).get("key", {})
    local = key.get("Local") or {}
    return local.get("verbatim_path") or local.get("given_path") or "<unknown>"


def normalise_feature(text: str) -> str:
    text = SHA_RE.sub("<sha>", text)
    text = VERSION_COMMENT_RE.sub("", text)
    return WS_RE.sub(" ", text).strip()


def fingerprint(finding: dict) -> dict:
    loc = _primary(finding)
    path = _path(loc)
    annotation = loc.get("symbolic", {}).get("annotation", "")
    feature = normalise_feature(loc.get("concrete", {}).get("feature", ""))
    digest = hashlib.sha256(
        "\x1f".join([finding.get("ident", ""), path, annotation, feature]).encode()
    ).hexdigest()[:16]
    row = loc.get("concrete", {}).get("location", {}).get("start_point", {}).get("row")
    return {
        "fingerprint": digest,
        "ident": finding.get("ident", ""),
        "path": path,
        "severity": finding.get("determinations", {}).get("severity", ""),
        "line": None if row is None else row + 1,
    }


def run_zizmor(zizmor: str, paths: list[str]) -> list[dict]:
    cmd = [zizmor, "--offline", "--no-progress", "--format", "json", *paths]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    except FileNotFoundError:
        print(f"zizmor not found ({zizmor}); install the pinned version first",
              file=sys.stderr)
        raise SystemExit(2)
    # zizmor exits non-zero when it has findings; a JSON array on stdout is success.
    try:
        data = json.loads(proc.stdout or "null")
    except json.JSONDecodeError:
        data = None
    if not isinstance(data, list):
        sys.stderr.write(proc.stderr[-2000:])
        print(f"zizmor did not return a JSON findings list (exit {proc.returncode})",
              file=sys.stderr)
        raise SystemExit(2)
    return data


def current_entries(findings: list[dict]) -> list[dict]:
    entries = [fingerprint(f) for f in findings if not f.get("ignored")]
    return sorted(entries, key=lambda e: (e["path"], e["ident"], e["fingerprint"]))


def load_baseline(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return json.loads(path.read_text())["findings"]


def write_baseline(path: Path, entries: list[dict]) -> None:
    payload = {
        "$comment": "Generated by scripts/workflow-security-ratchet.py --write-baseline. "
                    "Known zizmor findings; new ones fail CI. Shrink this, never hand-add.",
        "findings": [{k: e[k] for k in ("fingerprint", "ident", "path", "severity")}
                     for e in entries],
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n")


def compare(current: list[dict], baseline: list[dict]) -> tuple[list[dict], list[dict]]:
    cur = Counter(e["fingerprint"] for e in current)
    base = Counter(e["fingerprint"] for e in baseline)
    new_counts, gone_counts = cur - base, base - cur
    new, gone = [], []
    for e in current:
        if new_counts[e["fingerprint"]] > 0:
            new.append(e)
            new_counts[e["fingerprint"]] -= 1
    for e in baseline:
        if gone_counts[e["fingerprint"]] > 0:
            gone.append(e)
            gone_counts[e["fingerprint"]] -= 1
    return new, gone


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("paths", nargs="*", default=DEFAULT_PATHS)
    ap.add_argument("--baseline", type=Path, default=DEFAULT_BASELINE)
    ap.add_argument("--write-baseline", action="store_true")
    ap.add_argument("--zizmor", default="zizmor")
    ap.add_argument("--input", type=Path, help="Precomputed zizmor JSON output")
    args = ap.parse_args(argv)

    paths = [p for p in args.paths if Path(p).exists()]
    findings = (json.loads(args.input.read_text()) if args.input
                else run_zizmor(args.zizmor, paths))
    current = current_entries(findings)

    if args.write_baseline:
        write_baseline(args.baseline, current)
        print(f"Wrote {len(current)} finding(s) to {args.baseline}")
        return 0

    new, gone = compare(current, load_baseline(args.baseline))
    for e in new:
        line = f",line={e['line']}" if e.get("line") else ""
        print(f"::error file={e['path']}{line}::zizmor {e['ident']} ({e['severity']}): "
              "new workflow-security finding — fix it (preferred) or justify and "
              "regenerate the baseline")
    for e in gone:
        print(f"::error file={e['path']}::zizmor {e['ident']} no longer present — "
              "run --write-baseline to shrink the baseline")
    if new or gone:
        print(f"{len(new)} new, {len(gone)} resolved-but-still-baselined finding(s)",
              file=sys.stderr)
        return 1
    print(f"OK: {len(current)} known finding(s), none new")
    return 0


if __name__ == "__main__":
    sys.exit(main())
